import { chromium } from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.getByText('The first page is still to come.').waitFor();
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'docs/review/backend-home.png',fullPage:true});
await page.getByRole('link',{name:'Author sign in',exact:true}).click();
await page.getByRole('heading',{name:'Hello, Charlieb.'}).waitFor();
await page.screenshot({path:'docs/review/sign-in.png',fullPage:true});
await page.goto('http://127.0.0.1:5173/write');
await page.waitForURL('**/signin');
await page.getByRole('heading',{name:'Hello, Charlieb.'}).waitFor();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'docs/review/sign-in-mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
await page.goto('http://127.0.0.1:5173/posts/no-such-post');
await page.getByRole('heading',{name:'A little lost?'}).waitFor();
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button',{name:'Switch to dark mode'}).click();
await page.reload();
if(await page.locator('html').getAttribute('data-theme')!=='dark')throw Error('Theme lost');
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: live empty state, sign-in route, protected editor redirect, 404, mobile layout, theme persistence, no browser errors.');
await browser.close();
