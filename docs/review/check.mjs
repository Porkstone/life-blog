import { chromium } from '@playwright/test';
const browser = await chromium.launch({channel:'msedge',headless:true});
const page = await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173'); await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'docs/review/desktop-light.png',fullPage:true});
await page.getByRole('button',{name:'Switch to dark mode'}).click();
await page.reload();
if(await page.locator('html').getAttribute('data-theme')!=='dark')throw Error('Theme did not persist');
await page.screenshot({path:'docs/review/desktop-dark.png',fullPage:true});
await page.getByRole('button',{name:'Technology',exact:true}).click();
if(await page.locator('.post-row').count()!==1)throw Error('Filter failed');
await page.locator('.post-row').click();
await page.locator('.prose').waitFor();
await page.reload(); await page.locator('.prose').waitFor();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'docs/review/mobile-article.png',fullPage:true});
await page.goto('http://127.0.0.1:5173');
await page.getByRole('button',{name:'Switch to light mode'}).click();
await page.screenshot({path:'docs/review/mobile-light.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
await page.getByRole('link',{name:'About',exact:true}).click();
await page.locator('.about').waitFor();
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS: filters, article navigation and reload, theme persistence, about, mobile overflow, no browser errors.');
await browser.close();
